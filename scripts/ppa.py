"""Extract scalar results and path endpoints from locally supplied Genus reports."""
import argparse
from pathlib import Path
import re
from arithmetic import ROOT, write_csv

MAP = {
    "lfa": ("LFA (syn)", ("lfa", "lfaapprox2", "LADNER_Approx2", "lfaapprox8", "lfa_csa")),
    "ksa": ("KSA(syn)", ("ksa", "ksaapprox2", "ksaapprox4", "ksaapprox8", "ksa_csa")),
    "bka": ("BKA(syn)", ("BK", "BKapprox2", "BKapprox4", "BKapprox8", "BKA_CSA")),
}
FLAGS = {
    "lfa-2": "same exact top and identical metrics as lfa-exact",
    "lfa-4": "summary labels 4; report top and stem say Approx2",
    "lfa-8": "top matches; no submitted netlist fingerprint",
    "ksa-2": "same top and scalar values as ksa-4 and ksa-8",
    "ksa-4": "same top and scalar values as ksa-2 and ksa-8",
    "ksa-8": "same top and scalar values as ksa-2 and ksa-4",
    "bka-4": "timing report missing; summary says 1463 ps",
    "bka-8": "report top says BKapprox4; power duplicates bka-4",
    "ksa-exact": "report top ksa; recovered top kogge_stone_fig4",
    "bka-exact": "report top BK; recovered top Brkung",
}


def extract(folder):
    rows = []
    for arch, (dirname, names) in MAP.items():
        for variant, stem in zip(("exact","2","4","8","csa"),names,strict=True):
            label = f"{arch}-{variant}"
            path = folder / dirname
            area = (path / f"_{stem}_area.rep").read_text()
            power = (path / f"{stem}_power.rep").read_text()
            timing_path = path / f"{stem}_timing.rep"
            timing = timing_path.read_text() if timing_path.exists() else ""
            area_top = field(area, r"Module:\s+(\S+)")
            cells = re.search(rf"^\s*{re.escape(area_top)}\s+(\d+)\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)", area, re.M)
            terms = re.search(r"^\s*Subtotal\s+(\S+)\s+(\S+)\s+(\S+)\s+(\S+)",power,re.M)
            row = dict(design=label, report_stem=stem, area_top=area_top,
                       power_top=field(power,r"Instance:\s+/(\S+)"),
                       timing_top=field(timing,r"Module:\s+(\S+)"),
                       cells=int(cells[1]), cell_area=float(cells[2]),
                       net_area=float(cells[3]), total_area=float(cells[4]),
                       leakage_w=float(terms[1]), internal_w=float(terms[2]),
                       switching_w=float(terms[3]), total_w=float(terms[4]),
                       path_ps=field(timing,r"Data Path:\s*-\s*(\d+)"),
                       path_condition=field(timing,r"Path 1:\s+(\S+)"),
                       startpoint=field(timing,r"Startpoint:\s+\([^)]+\)\s+(\S+)"),
                       endpoint=field(timing,r"Endpoint:\s+\([^)]+\)\s+(\S+)"),
                       timing_cells=" > ".join(re.findall(
                           r"^\s+\S+\s+-\s+\S+->\S+\s+[RF]\s+(\w+)\s+\d+", timing,re.M)),
                       tool=field(area,r"Generated by:\s+([^\r\n]+)"),
                       corner=field(area,r"Operating conditions:\s+([^\r\n]+)"),
                       wireload=field(area,r"Wireload mode:\s+(\S+)"),
                       power_frame=field(power,r"PDB Frames:\s+(\S+)"),
                       attribution=FLAGS.get(label,"archived label; no netlist fingerprint"))
            if variant == "exact":
                baseline = row
            row["power_reduction_pct"] = 100*(1-row["total_w"]/baseline["total_w"])
            row["area_reduction_pct"] = 100*(1-row["cell_area"]/baseline["cell_area"])
            row["delay_reduction_pct"] = (
                100*(1-int(row["path_ps"])/int(baseline["path_ps"])) if row["path_ps"] else "")
            rows.append(row)
    return rows


def field(text, pattern):
    match = re.search(pattern,text)
    return match[1].strip() if match else ""


def extract_legacy(folder):
    names = ("EXACT LFA REPORT.txt", "REPORT APPROX 2 (LFA).txt",
             "APPROX4 REPORT (LFA).txt", "APPROX 8 REPORT (LFA).txt")
    rows = []
    for variant,name in zip(("exact","2","4","8"),names,strict=True):
        report = (folder/name).read_text(encoding="utf-8-sig")
        top = field(report,r"Module:\s+(\S+)")
        cells = re.search(rf"^\s*{re.escape(top)}\s+(\d+)\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)",report,re.M)
        terms = re.search(r"^\s*Subtotal\s+(\S+)\s+(\S+)\s+(\S+)\s+(\S+)",report,re.M)
        rows.append(dict(variant=variant, source=name, top=top, cells=int(cells[1]),
                         cell_area=float(cells[2]), leakage_w=float(terms[1]),
                         internal_w=float(terms[2]), switching_w=float(terms[3]),
                         total_w=float(terms[4]), path_ps=field(report,r"Data Path:\s*-\s*(\d+)"),
                         path_condition=field(report,r"Path 1:\s+(\S+)"),
                         startpoint=field(report,r"Startpoint:\s+\([^)]+\)\s+(\S+)"),
                         endpoint=field(report,r"Endpoint:\s+\([^)]+\)\s+(\S+)"),
                         report_date=field(report,r"Generated on:\s+([^\r\n]+)")))
    return rows


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("reports", type=Path)
    parser.add_argument("--legacy", type=Path, help="folder containing the four older LFA reports")
    args = parser.parse_args()
    write_csv(ROOT / "results/genus.csv", extract(args.reports))
    if args.legacy:
        write_csv(ROOT / "results/genus_legacy_lfa.csv",extract_legacy(args.legacy))
